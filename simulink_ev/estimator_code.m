function c = estimator_code(which)
%ESTIMATOR_CODE  Source of the 1 Hz estimator MATLAB Function blocks.
%   Used by build_EV_BMS_SOC_Estimation_System.m. Kept in one file so that the
%   code inserted into the model is easy to read and review. Every block loads
%   its constants at compile time from SOC_Estimator_Params.mat (coder.load),
%   the same numbers the Python pipeline uses.
switch which
case 'ekf'
c = strjoin({
'function [soc, T_core, T_amb_est, innov, S_v, P_soc, docv, soc0_out] = ElectroThermal_EKF(V, I, Ts)'
'%#codegen'
'% Electro-thermal EKF, 1 Hz. x = [SOC V1 V2 T_core T_surf T_amb], z = [V; T_surf].'
'% Parameters scheduled on the estimated core temperature (falls back to the'
'% measured surface temperature after a thermal event the model cannot follow).'
'E = coder.load(''SOC_Estimator_Params.mat'');   % compile-time constants'
'persistent x P h w s0 init'
'if isempty(init)'
'    s0 = soc_from_v(E, V, Ts);                     % key-on SOC from the rested OCV'
'    x = [s0; 0; 0; Ts; Ts; Ts]; P = diag(E.ekf_P0); h = 0; w = 1; init = 1;'
'end'
'dt = 1;'
'soc0_out = s0;'
'% ---------------- measurement update ----------------'
'Tel = w*x(4) + (1-w)*Ts;'
'[v, ds, ~] = lut2(E, x(1), Tel);'
'M = interp1(E.T_bp, E.hyst_M_T, min(max(Tel,E.T_bp(1)),E.T_bp(end)));'
'I0 = interp1(E.T_bp, E.I0_T, min(max(Tel,E.T_bp(1)),E.T_bp(end)));'
'eta_ct = 2*8.314462618*(Tel + 273.15)/96485.33212*asinh(I/(2*I0));   % Butler-Volmer'
'yv = v(1) + M*h - I*v(2) - eta_ct - x(2) - x(3);'
'H = zeros(2,6); H(1,1) = ds(1) - I*ds(2); H(1,2) = -1; H(1,3) = -1; H(2,5) = 1;'
'Rm = diag([E.ekf_Rv, E.ekf_Rt]);'
'e = [V; Ts] - [yv; x(5)];'
'st = P(5,5) + Rm(2,2);'
'if e(2)^2/st > E.ekf_nis_gate'
'    P(6,6) = P(6,6) + 0.5*e(2)^2; P(5,5) = P(5,5) + 0.25*e(2)^2; w = 0;'
'end'
'S = H*P*H.'' + Rm;'
'K = P*H.''/S;'
'x = x + K*e;'
'x(1) = min(max(x(1), 0), 1);'
'A = eye(6) - K*H;'
'P = A*P*A.'' + K*Rm*K.'';'
'soc = x(1); T_core = x(4); T_amb_est = x(6); innov = e(1); S_v = S(1,1);'
'P_soc = P(1,1); docv = ds(1);'
'% ---------------- time update ----------------'
'Tel = w*x(4) + (1-w)*Ts;'
'[v, ds, dT] = lut2(E, x(1), Tel);'
'R0 = v(2); R1 = v(3); t1 = max(v(4),1e-3); R2 = v(5); t2 = max(v(6),1e-3);'
'a1 = exp(-dt/t1); a2 = exp(-dt/t2);'
'if I >= 0, eta = 1; else, eta = E.eta_chg; end'
'dudt = interp1(E.soc_bp, E.dudt, min(max(x(1),0),1));'
'I0 = interp1(E.T_bp, E.I0_T, min(max(Tel,E.T_bp(1)),E.T_bp(end)));'
'eta_ct = 2*8.314462618*(Tel + 273.15)/96485.33212*asinh(I/(2*I0));'
'Q = I^2*R0 + I*eta_ct + I*(x(2) + x(3)) - I*(x(4) + 273.15)*dudt;'
'F = eye(6); F(2,2) = a1; F(3,3) = a2;'
'dT = dT*w;'
'da1 = a1*dt/t1^2*dT(4); da2 = a2*dt/t2^2*dT(6);'
'F(2,4) = (x(2) - R1*I)*da1 + (1 - a1)*I*dT(3);'
'F(3,4) = (x(3) - R2*I)*da2 + (1 - a2)*I*dT(5);'
'xn = zeros(6,1);'
'xn(1) = x(1) - eta*I*dt/(3600*E.Cn);'
'xn(2) = a1*x(2) + R1*(1 - a1)*I;'
'xn(3) = a2*x(3) + R2*(1 - a2)*I;'
'zt = E.Ad*[x(4); x(5)] + E.Bd*[Q; x(6)];'
'xn(4) = zt(1); xn(5) = zt(2); xn(6) = min(max(x(6), -40), 70);'
'dQ = [I^2*ds(2), I, I, I^2*dT(2) - I*dudt, 0, 0];'
'for r = 1:2'
'    F(3+r,:) = E.Bd(r,1)*dQ;'
'    F(3+r,4) = F(3+r,4) + E.Ad(r,1);'
'    F(3+r,5) = F(3+r,5) + E.Ad(r,2);'
'    F(3+r,6) = F(3+r,6) + E.Bd(r,2);'
'end'
'x = xn;'
'P = F*P*F.'' + diag(E.ekf_Q);'
'w = 1 - E.ekf_trust_decay*(1 - w);'
'if I ~= 0'
'    ee = exp(-abs(I)*dt*E.hyst_gamma/(3600*E.Cn));'
'    h = ee*h - (1 - ee)*sign(I);'
'end'
'end'
''
'function [val, ds, dT] = lut2(E, soc, T)'
'% bilinear lookup of the 6 tables (OCV R0 R1 tau1 R2 tau2) and its partials'
'sb = E.soc_bp; tb = E.T_bp; ns = numel(sb); nt = numel(tb);'
's = min(max(soc, sb(1)), sb(ns)); t = min(max(T, tb(1)), tb(nt));'
'i = 1; while i < ns-1 && s >= sb(i+1), i = i + 1; end'
'j = 1; while j < nt-1 && t >= tb(j+1), j = j + 1; end'
'u = (s - sb(i))/(sb(i+1) - sb(i)); q = (t - tb(j))/(tb(j+1) - tb(j));'
'val = zeros(6,1); ds = zeros(6,1); dT = zeros(6,1);'
'for k = 1:6'
'    f00 = E.tab(k,i,j); f10 = E.tab(k,i+1,j); f01 = E.tab(k,i,j+1); f11 = E.tab(k,i+1,j+1);'
'    val(k) = f00*(1-u)*(1-q) + f10*u*(1-q) + f01*(1-u)*q + f11*u*q;'
'    ds(k) = ((f10 - f00)*(1-q) + (f11 - f01)*q)/(sb(i+1) - sb(i));'
'    dT(k) = ((f01 - f00)*(1-u) + (f11 - f10)*u)/(tb(j+1) - tb(j));'
'end'
'end'
''
'function s0 = soc_from_v(E, V, T)'
'% rested-OCV inversion for the key-on initial SOC (linear interpolation'
'% on a 401-point grid of the OCV curve at the measured temperature)'
'cv = zeros(401,1); g = (0:400).''/400;'
'for k = 1:401'
'    [v, ~, ~] = lut2(E, g(k), T); cv(k) = v(1);'
'end'
'if V <= cv(1)'
'    s = 0;'
'elseif V >= cv(401)'
'    s = 1;'
'else'
'    k = 1; while cv(k+1) < V, k = k + 1; end'
'    s = g(k) + (V - cv(k))/(cv(k+1) - cv(k))*(g(k+1) - g(k));'
'end'
's0 = min(max(s, 0.02), 0.98);'
'end'}, newline);

case 'cnn'
c = strjoin({
'function [soc_cnn, valid, d2, zmax] = CNN_SOC_Estimator(V, I, T)'
'%#codegen'
'% 1-D CNN SOC estimator, 1 Hz. Sliding 240 s window of 7 channels:'
'% v, i, t, i_ma (trailing 60 s mean), ah_cum (window-relative / Cn),'
'% dv (first difference), v_ir = v + i*R0_nom. Conv(16,k5)-BN-ReLU-Pool2,'
'% Conv(32,k5)-BN-ReLU-Pool2, Conv(64,k3)-BN-ReLU, GAP, Dense32-ReLU, Dense1-sigmoid.'
'N = coder.load(''SOC_Estimator_Params.mat'');   % weights: compile-time constants'
'persistent buf ibuf ah n vprev'
'if isempty(n)'
'    buf = zeros(240, 7); ibuf = zeros(60, 1); ah = zeros(240, 1); n = 0; vprev = V;'
'end'
'L = 240;'
'n = n + 1;'
'ibuf = [ibuf(2:end); I];'
'ima = sum(ibuf(max(1, 61 - n):60))/min(n, 60);'
'ahg = 0;'
'if n > 1, ahg = ah(end); end'
'ahg = ahg + I*1/3600;'
'ah = [ah(2:end); ahg];'
'if n == 1, dv = 0; else, dv = V - vprev; end'
'vprev = V;'
'buf = [buf(2:end,:); [V, I, T, ima, 0, dv, V + I*N.feat_R0]];'
'valid = double(n >= L);'
'soc_cnn = 0; d2 = 0; zmax = 0;'
'if n < L, return; end'
'X = buf;'
'X(:,5) = (ah - ah(1))/N.feat_Cn;'
'X = (X - repmat(N.nz_mean, L, 1)) ./ repmat(N.nz_std, L, 1);'
'% out-of-distribution statistics on the window-mean feature vector'
'f = mean(X, 1);'
'dd = f - N.ood_mu;'
'd2 = dd*N.ood_inv*dd.'';'
'zmax = max(abs(dd ./ N.ood_sd));'
'% ---- network ----'
'a = conv_bn_relu(X, N.W1, N.b1, N.g1, N.be1, N.m1, N.v1, 5);'
'a = maxpool2(a);'
'a = conv_bn_relu(a, N.W2, N.b2, N.g2, N.be2, N.m2, N.v2, 5);'
'a = maxpool2(a);'
'a = conv_bn_relu(a, N.W3, N.b3, N.g3, N.be3, N.m3, N.v3, 3);'
'g = mean(a, 1);'
'h1 = max(g*N.W4 + N.b4, 0);'
'z = h1*N.W5 + N.b5;'
'soc_cnn = 1/(1 + exp(-min(max(z, -40), 40)));'
'end'
''
'function y = conv_bn_relu(x, W, b, gam, bet, mu, va, k)'
'% valid 1-D convolution, W is (k*Cin) x Cout with row index (j-1)*Cin + c'
'[Lx, C] = size(x); Lo = Lx - k + 1; Co = size(W, 2);'
'y = repmat(b, Lo, 1);'
'for j = 1:k'
'    y = y + x(j:j+Lo-1, :)*W((j-1)*C+1:j*C, :);'
'end'
'y = (y - repmat(mu, Lo, 1)) ./ repmat(sqrt(va + 1e-5), Lo, 1) .* repmat(gam, Lo, 1) + repmat(bet, Lo, 1);'
'y = max(y, 0);'
'end'
''
'function y = maxpool2(x)'
'[Lx, C] = size(x); Lt = floor(Lx/2);'
'y = zeros(Lt, C);'
'for r = 1:Lt'
'    y(r,:) = max(x(2*r-1,:), x(2*r,:));'
'end'
'end'}, newline);

case 'fusion'
c = strjoin({
'function [soc_adaptive, soc_fixed, alpha, conf_ekf, conf_cnn, soc_cc] = Adaptive_Fusion(soc_ekf, innov, S_v, P_soc, docv, soc_cnn, valid, d2, zmax, I, soc0)'
'%#codegen'
'% Confidence-based adaptive fusion, 1 Hz:'
'%   alpha = rho*c_ekf^beta / (rho*c_ekf^beta + c_cnn^beta), slew-limited'
'%   SOC = alpha*SOC_ekf + (1-alpha)*SOC_cnn'
'% c_ekf: innovation consistency, covariance, observability (|dOCV/dSOC|)'
'% c_cnn: prediction stability, agreement with Coulomb-counted dSOC, in-distribution'
'F = coder.load(''SOC_Estimator_Params.mat'');'
'persistent a cc hist cch n'
'if isempty(n)'
'    a = 1; cc = soc0; hist = zeros(10,1); cch = zeros(10,1); n = 0;'
'end'
'eps0 = F.fu_eps;'
'% Coulomb counting (baseline, and the physics check for the CNN), from the EKF key-on SOC'
'soc_cc = min(max(cc, 0), 1);'
'% ---- EKF confidence ----'
'zi = innov/sqrt(max(S_v, 1e-12));'
'f_in = exp(-0.5*(zi/F.fu_innov_k)^2);'
'f_cov = exp(-P_soc/F.fu_P_ref);'
'f_obs = min(max(abs(docv)/F.fu_g_ref, 0), 1);'
'conf_ekf = wgeom([f_in f_cov f_obs], [1 1 1.5], eps0);'
'% ---- CNN confidence ----'
'conf_cnn = 0;'
'if valid > 0'
'    n = n + 1;'
'    hist = [hist(2:end); soc_cnn]; cch = [cch(2:end); soc_cc];'
'    m = min(n, 10);'
'    if m >= 2'
'        seg = hist(11-m:10);'
'        f_st = exp(-std(seg, 1)/F.fu_stab_ref);'
'        f_ph = exp(-abs((hist(10) - hist(11-m)) - (cch(10) - cch(11-m)))/F.fu_phys_ref);'
'    else'
'        f_st = 1; f_ph = 1;'
'    end'
'    f_ood = 1/(1 + (max(d2,0)/F.ood_ref_d2)^3) / (1 + (max(zmax,0)/F.ood_ref_z)^3);'
'    conf_cnn = wgeom([f_st f_ph f_ood], [1 1 1.5], eps0);'
'    cp = max(conf_ekf, eps0); cm = max(conf_cnn, eps0);'
'    wp = F.fu_rho*cp^F.fu_beta; wm = cm^F.fu_beta;'
'    alpha_raw = wp/(wp + wm);'
'else'
'    alpha_raw = 1;'
'end'
'a = a + min(max(alpha_raw - a, -F.fu_slew), F.fu_slew);'
'alpha = a;'
'if valid > 0'
'    soc_adaptive = min(max(alpha*soc_ekf + (1 - alpha)*soc_cnn, 0), 1);'
'    soc_fixed = min(max(0.5*soc_ekf + 0.5*soc_cnn, 0), 1);'
'else'
'    soc_adaptive = soc_ekf; soc_fixed = soc_ekf;'
'end'
'% advance Coulomb counter'
'if I >= 0, eta = 1; else, eta = F.cc_eta_chg; end'
'cc = cc - eta*I/(3600*F.Cn);'
'end'
''
'function g = wgeom(t, wt, e)'
'g = exp(sum(wt .* log(max(t, e)))/sum(wt));'
'end'}, newline);
end
end
